"""B8 step 9 (B8-16, B8-17): the EU report's PDF, read back from its MIR file. Every value in the XML is in the PDF,
under its block's number and label; the title says MDARIX prepared it, never the Commission; a draft is marked; the
same file gives the same bytes. No database."""

from __future__ import annotations

import io

import pytest
from lxml import etree
from pypdf import PdfReader

from backend.app.authority_reports import forms, mir_pdf, mir_xml
from tests.test_b8_mir_xml import FULL, NOW, PARTIES

pytestmark = pytest.mark.unit

VIEW = {
    "complaint": {"ref": "SAMPLE-RV-07", "product_name": "VentraLink 250", "version": "Rev B"},
    "preparers": ["Sam Sample"],
    "practice_label": None,
    "sections": [],
}
SIGNATURE = {"signer_name": "Ada Approver", "signer_role": "QA/RA", "meaning": "Approved", "record_id": "R-1"}
SIGNED = {
    **VIEW,
    "signature": SIGNATURE
    | {"signed_at": "2026-11-12T10:00:00+00:00", "record_business_id": None, "content_fingerprint": "0" * 64},
}


def _xml(report_type: str = forms.MIR_FINAL) -> bytes:
    return mir_xml.build(FULL | {"1_2E": report_type}, PARTIES, report_type=report_type, now=NOW)


def _text(pdf: bytes) -> str:
    return "\n".join(page.extract_text() for page in PdfReader(io.BytesIO(pdf)).pages)


def test_b8_every_value_in_the_xml_is_in_the_pdf():
    xml = _xml()
    lines = [text for text, _ in mir_pdf.body(xml)]
    shown = "\n".join(lines)
    leaves = [e for e in etree.fromstring(xml).iter() if len(e) == 0 and (e.text or "").strip()]
    assert leaves and all(leaf.text.strip() in shown for leaf in leaves)
    for heading in mir_pdf.SECTIONS.values():
        assert heading in lines
    assert "1.2f In case of initial and follow-up reports, please indicate the expected date of next report" in lines
    assert "    Period N-3 · World sim dev: 36000" in lines
    assert "    Authorised representative · AR city: Lyon" in lines
    assert lines.index("2 Medical device information") < lines.index("3 Incident information")


def test_b8_the_pdf_never_says_the_commission_made_it():
    text = _text(mir_pdf.render(_xml(), SIGNED, "Orbit Medical Devices (Sample)"))
    assert mir_pdf.TITLE in text and "EU MIR CONTENT - PREPARED BY MDARIX" in text
    lowered = text.lower()
    for claim in (
        "generated by the commission",
        "made by the commission",
        "by the european commission",
        "eudamed made",
    ):
        assert claim not in lowered, claim
    assert "MDARIX never submits" in text and "SHA-256 of the MIR file" in text


def test_b8_a_draft_pdf_is_marked_draft():
    from backend.app.authority_reports.render import PREVIEW_LINE

    assert PREVIEW_LINE in _text(mir_pdf.render(_xml(), VIEW, None))
    assert PREVIEW_LINE not in _text(mir_pdf.render(_xml(), SIGNED, None))


def test_b8_same_snapshot_same_pdf_bytes():
    xml = _xml(forms.MIR_INITIAL)
    assert mir_pdf.render(xml, SIGNED, "Orbit") == mir_pdf.render(xml, SIGNED, "Orbit")
